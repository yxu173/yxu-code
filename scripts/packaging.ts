/**
 * Package-manager manifests for a release, from dist/release/checksums.txt:
 *   dist/packaging/yxu.rb     Homebrew formula (tap: yxu173/homebrew-tap)
 *   dist/packaging/PKGBUILD   AUR package `yxu-bin`
 *   dist/packaging/.SRCINFO
 *
 * usage: bun scripts/packaging.ts [--version X.Y.Z] [--checksums path]
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

const ROOT = join(import.meta.dir, "..");
const REPO = "yxu173/yxu-code";
const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));

const { values } = parseArgs({ options: { version: { type: "string" }, checksums: { type: "string" } } });
const version = (values.version ?? pkg.version).replace(/^v/, "");
const sums = new Map(
  readFileSync(values.checksums ?? join(ROOT, "dist", "release", "checksums.txt"), "utf8")
    .trim()
    .split("\n")
    .map((l) => l.trim().split(/\s+/) as [string, string])
    .map(([hash, file]) => [file, hash]),
);
const sha = (target: string) => {
  const h = sums.get(`yxu-${target}.tar.gz`);
  if (!h) throw new Error(`checksums.txt has no entry for yxu-${target}.tar.gz`);
  return h;
};
const url = (target: string) => `https://github.com/${REPO}/releases/download/v${version}/yxu-${target}.tar.gz`;
const desc = pkg.description as string;

const formula = `# Generated by scripts/packaging.ts for v${version}. Do not edit by hand.
class Yxu < Formula
  desc "${desc.replace(/"/g, '\\"')}"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${url("darwin-arm64")}"
      sha256 "${sha("darwin-arm64")}"
    end
    on_intel do
      url "${url("darwin-x64")}"
      sha256 "${sha("darwin-x64")}"
    end
  end

  on_linux do
    on_arm do
      url "${url("linux-arm64")}"
      sha256 "${sha("linux-arm64")}"
    end
    on_intel do
      url "${url("linux-x64")}"
      sha256 "${sha("linux-x64")}"
    end
  end

  def install
    bin.install "yxu"
  end

  def caveats
    <<~EOS
      yxu needs Claude Code (\`claude\`) installed and logged in, plus at least one
      agent CLI (opencode, cmd or claude). Run \`yxu doctor\` in a git repo to check.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/yxu --version")
  end
end
`;

const pkgbuild = `# Maintainer: yxu173 <https://github.com/yxu173>
# Generated by scripts/packaging.ts for v${version}. Do not edit by hand.
pkgname=yxu-bin
pkgver=${version.replace(/-/g, "_")}
pkgrel=1
pkgdesc="${desc.replace(/"/g, '\\"')}"
arch=('x86_64' 'aarch64')
url="https://github.com/${REPO}"
license=('MIT')
depends=('git')
optdepends=('claude-code: orchestrator engine (required at run time)'
            'opencode: subagent CLI')
provides=('yxu')
conflicts=('yxu')
options=('!strip' '!debug')
source_x86_64=("yxu-${version}-x86_64.tar.gz::${url("linux-x64")}")
source_aarch64=("yxu-${version}-aarch64.tar.gz::${url("linux-arm64")}")
sha256sums_x86_64=('${sha("linux-x64")}')
sha256sums_aarch64=('${sha("linux-arm64")}')

package() {
  install -Dm755 yxu "$pkgdir/usr/bin/yxu"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 README.md "$pkgdir/usr/share/doc/$pkgname/README.md"
}
`;

const srcinfo = `pkgbase = yxu-bin
\tpkgdesc = ${desc}
\tpkgver = ${version.replace(/-/g, "_")}
\tpkgrel = 1
\turl = https://github.com/${REPO}
\tarch = x86_64
\tarch = aarch64
\tlicense = MIT
\tdepends = git
\toptdepends = claude-code: orchestrator engine (required at run time)
\toptdepends = opencode: subagent CLI
\tprovides = yxu
\tconflicts = yxu
\toptions = !strip
\toptions = !debug
\tsource_x86_64 = yxu-${version}-x86_64.tar.gz::${url("linux-x64")}
\tsha256sums_x86_64 = ${sha("linux-x64")}
\tsource_aarch64 = yxu-${version}-aarch64.tar.gz::${url("linux-arm64")}
\tsha256sums_aarch64 = ${sha("linux-arm64")}

pkgname = yxu-bin
`;

const out = join(ROOT, "dist", "packaging");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "yxu.rb"), formula);
writeFileSync(join(out, "PKGBUILD"), pkgbuild);
writeFileSync(join(out, ".SRCINFO"), srcinfo);
console.log(`wrote Homebrew formula and AUR PKGBUILD for v${version} → dist/packaging`);
